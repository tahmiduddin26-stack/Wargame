/**
 * Twenty units: five ages by four roles.
 *
 * Balance intent, held constant across every age so the roster reads the same
 * once you have learned it:
 *   melee     cheapest gold-per-hitpoint, must close the gap to do anything
 *   ranged    outranges melee, folds the moment something reaches it
 *   heavy     the push. Expensive, knocks the enemy line backwards
 *   artillery outranges turrets, splash, dies to a stiff breeze
 *
 * Each age is roughly 2.4x the combat power and 3x the cost of the one below,
 * so evolving is always worth more than buying wider at your current age.
 *
 * The number that matters most is TIME TO KILL. Same-age melee kill each other
 * in about 2.2 seconds, which is deliberately fast:
 *
 *   melee dps = melee hp / 2.2      ranged  = 0.85x melee dps, 0.55x its hp
 *   heavy     = 2.2x melee dps, 3.2x hp    artillery = splash, 1.1x hp
 *
 * Slower than that and neither side can ever clear the other's front line, so
 * both commanders feed reinforcements into a stalemate at the midpoint until the
 * clock runs out. A short TTK is what lets a numbers or age advantage compound
 * into an actual push. Bounty is ~1.1x cost and loot ~0.48x cost, so winning
 * fights, not passive income, is what funds the next wave.
 */
