export const UNIT_BY_ID: Record<string, UnitDef> = UNITS.reduce<Record<string, UnitDef>>(
  (acc, unit) => {
    acc[unit.id] = unit;
    return acc;
  },
  {},
);

/** Roster for one age, always ordered melee, ranged, heavy, artillery. */
const ROLE_ORDER: UnitRole[] = ['melee', 'ranged', 'heavy', 'artillery'];

export function unitsForAge(age: AgeId): UnitDef[] {
  return UNITS.filter((u) => u.age === age).sort(
    (a, b) => ROLE_ORDER.indexOf(a.role) - ROLE_ORDER.indexOf(b.role),
  );
}

export function unitsUpToAge(ageIndex: number, ages: AgeId[]): UnitDef[] {
  const allowed = new Set(ages.slice(0, ageIndex + 1));
  return UNITS.filter((u) => allowed.has(u.age));
}

